def _build_location_to_province_map(tree) -> dict:
    """Build a mapping from location -> province key by walking the eu5 map tree.

    The tree is a nested dict/Tree structure where the smallest keys are location
    identifiers and their parent is the province (the second-smallest tier).
    """
    mapping: dict = {}

    def walk(node, parent=None):
        # pyradox.Tree behaves like dict
        if isinstance(node, (_pydt.Tree, dict)):
            for k, v in node.items():
                if isinstance(v, (_pydt.Tree, dict)):
                    # k is a grouping key (could be province or higher); recurse
                    walk(v, k)
                elif isinstance(v, list):
                    # list of scalar locations or subtrees
                    for item in v:
                        if isinstance(item, (_pydt.Tree, dict)):
                            walk(item, k)
                        else:
                            mapping[str(item)] = k
                else:
                    # leaf value: k is likely a location name, parent is province
                    mapping[str(k)] = parent if parent is not None else k
        elif isinstance(node, list):
            for item in node:
                walk(item, parent)

    walk(tree, None)
    return mapping


def audit_country_locations(
    ten_countries_data: dict,
    country_data: list,
    eu5_map_data,
) -> None:
    """
    Audit own_control_core locations and capitals after writing 10_countries.

    Reports:
    - locations assigned to multiple country tags (only valid locations)
    - locations not present in the map (unknown)
    - capitals not present in the map (unknown)
    """

    location_to_province = (
        _build_location_to_province_map(eu5_map_data)
        if eu5_map_data is not None
        else {}
    )

    owners: dict[str, set[str]] = defaultdict(set)
    unknown_locations: list[tuple[str, str]] = []
    unknown_capitals: list[tuple[str, str]] = []

    for country in country_data:
        tag = country["tag"]
        base = ten_countries_data.get(tag, {})

        # --- own_control_core ---
        value = base.get("own_control_core", [])
        locations = (
            [] if value is None else value if isinstance(value, list) else [value]
        )

        for loc in locations:
            loc_key = str(loc)
            if loc_key not in location_to_province:
                unknown_locations.append((loc_key, tag))
            else:
                owners[loc_key].add(tag)

        # --- capital ---
        capital = base.get("capital")
        if capital:
            cap_key = str(capital)
            if cap_key not in location_to_province:
                unknown_capitals.append((cap_key, tag))
            else:
                owners[cap_key].add(tag)

    # --- REPORT ---
    conflicts = {loc: tags for loc, tags in owners.items() if len(tags) > 1}

    if not conflicts and not unknown_locations and not unknown_capitals:
        print(
            "Location audit: OK (no conflicts, no unknown locations, no unknown capitals)"
        )
        return

    print("\n=== LOCATION AUDIT REPORT ===")

    if conflicts:
        print("\nLocations assigned to multiple countries:")
        for loc, tags in sorted(conflicts.items()):
            print(f"  {loc}: {', '.join(sorted(tags))}")

    if unknown_locations:
        print("\nUnknown locations (own_control_core):")
        for loc, tag in sorted(unknown_locations):
            print(f"  {loc}: assigned to {tag}")

    if unknown_capitals:
        print("\nUnknown capitals:")
        for loc, tag in sorted(unknown_capitals):
            print(f"  {loc}: capital of {tag}")

    print("\n=== END LOCATION AUDIT ===\n")


def write_blocks_with_comments(
    out_path: Path,
    blocks: List[Tuple[str, List[object]]],
    comment_tags: set[str] | None = None,
    mode: str = "w",
    encoding: str = "utf-8",
    indent_str: str = "    ",
) -> Path:
    if comment_tags is None:
        comment_tags = set()

    def render_block(tag: str, lines: list, level: int = 0) -> list[str]:
        prefix = indent_str * level
        inner_prefix = indent_str * (level + 1)
        output: list[str] = []

        # Check if we need to comment out this entire block
        comment_block = tag in comment_tags

        # Opening line
        open_line = f"{prefix}{tag} = {{"
        if comment_block:
            open_line = "# " + open_line
        output.append(open_line)

        for line in lines:
            if isinstance(line, tuple) and len(line) == 2:
                subtag, sublines = line
                sublines_rendered = render_block(subtag, sublines, level + 1)
                if comment_block:
                    # Prefix every line of sub-block
                    sublines_rendered = [
                        f"# {l}" if not l.startswith("#") else l
                        for l in sublines_rendered
                    ]
                output.extend(sublines_rendered)
            else:
                l = f"{inner_prefix}{line}"
                if comment_block:
                    l = "# " + l if not l.startswith("#") else l
                output.append(l)

        # Closing brace
        close_line = f"{prefix}}}"
        if comment_block:
            close_line = "# " + close_line
        output.append(close_line)

        return output

    out_path.parent.mkdir(parents=True, exist_ok=True)

    with out_path.open(mode, encoding=encoding) as f:
        for block in blocks:
            if isinstance(block, tuple) and len(block) == 2:
                tag, lines = block
                rendered_lines = render_block(tag, lines, level=0)
                f.write("\n".join(rendered_lines) + "\n")
            else:
                # raw string block
                s = str(block)
                f.write(s)
                if not s.endswith("\n"):
                    f.write("\n")

    print_written("file", out_path)
    return out_path


def write_10_countries(
    ten_countries_data,
    country_data,
    eu5_map_data,
    country_rulers,
    culture_data=None,
    ir_country_locations=None,
    ir_country_capitals=None,
    id_to_key=None,
    location_keys=None,
):
    country_map = {country["tag"]: country for country in country_data}
    blocks = []
    comment_tags = set()

    rank_map = (
        _build_country_rank_map(ir_country_locations, country_data)
        if ir_country_locations is not None
        else {}
    )

    culture_to_group = {}
    if culture_data:
        for group in culture_data:
            group_tag = group.get("tag")
            for culture in group.get("cultures", []):
                culture_to_group[culture.get("tag")] = group_tag

    # build province mapping if provided
    location_to_province = (
        _build_location_to_province_map(eu5_map_data)
        if eu5_map_data is not None
        else {}
    )

    def normalize_value(value):
        if isinstance(value, str):
            v = value.strip()
            if len(v) >= 2 and v[0] == '"' and v[-1] == '"':
                return v[1:-1]
            return v
        return value

    for country in country_data:
        tag = country["tag"]
        country_name = country.get("name", tag)
        government_type = government_map[country_map[tag]["government"]]
        ruler = country_rulers.get(tag)  # optional override

        # --- start from base, preserve everything ---
        base = ten_countries_data.get(tag, {})
        merged = dict(base)  # shallow copy

        # --- own_control_core ---
        ir_locations = None
        if ir_country_locations is not None and id_to_key is not None:
            ir_locations = []
            for pid in ir_country_locations.get(tag, []):
                if pid in id_to_key:
                    loc = id_to_key.get(pid)
                    if loc is None:
                        continue
                    if location_keys is None or loc in location_keys:
                        ir_locations.append(loc)
        if ir_locations is not None:
            locations = ir_locations
        else:
            value = base.get("own_control_core", [])
            locations = (
                [] if value is None else value if isinstance(value, list) else [value]
            )

        if not locations:
            # force inline empty block (keep country enabled)
            merged["own_control_core"] = "{ }"
        else:
            prov_map: dict[str, list] = {}
            used_locations = set()  # track all locations globally

            for loc in locations:
                key = str(loc)
                if key in used_locations:
                    continue  # skip duplicates across provinces
                prov = location_to_province.get(key, "unknown")
                prov_map.setdefault(prov, []).append(key)
                used_locations.add(key)

            own_sublines: list[str] = []
            for prov, locs in sorted(prov_map.items()):
                own_sublines.append(f"# {prov}")
                own_sublines.append(" ".join(locs))

            merged["own_control_core"] = own_sublines

        # --- government (merge, override ruler if exists) ---
        base_government = base.get("government", {})
        if isinstance(base_government, _pydt.Tree):
            base_government = dict(base_government)
        if not isinstance(base_government, dict):
            base_government = {}
        merged_government = dict(base_government)  # copy existing fields

        if ruler:
            merged_government["ruler"] = ruler
        else:
            merged_government["ruler"] = base_government.get("ruler", "random")

        merged_government["type"] = government_type

        # --- include IR-specific starting government reform if available ---
        try:
            ir_gov_key = country_map[tag]["government"]
        except Exception:
            ir_gov_key = None

        if ir_gov_key:
            reform_id = f"ir_{ir_gov_key}"
            raw = merged_government.get("reforms", [])
            normalized = [str(item) for item in ensure_list(raw) if item not in (None, "")]
            normalized.append(reform_id)
            merged_government["reforms"] = _dedupe(normalized)

        merged["government"] = merged_government

        # --- court language ---
        culture_tag = country.get("culture")
        if culture_tag:
            court_language = ir_culture_language_overrides.get(culture_tag)
            if not court_language:
                group_tag = culture_to_group.get(culture_tag)
                if group_tag:
                    court_language = ir_culture_group_language_map.get(group_tag)
            if court_language:
                merged["court_language"] = court_language

        # --- include societal values template based on IR government type ---
        societal_template_keys = {
            "aristocratic_monarchy",
            "despotic_monarchy",
            "stratocratic_monarchy",
            "theocratic_monarchy",
            "aristocratic_republic",
            "democratic_republic",
            "oligarchic_republic",
            "plutocratic_republic",
            "tribal_chiefdom",
            "tribal_federation",
            "tribal_kingdom",
        }

        # --- includes (preserve all, normalize) ---
        raw_include = base.get("include", [])
        include_items = raw_include if isinstance(raw_include, list) else [raw_include]

        if "expl_imperator_rome" not in include_items:
            include_items = ["expl_imperator_rome", *include_items]

        if ir_gov_key in societal_template_keys:
            societal_template = f"ir_{ir_gov_key}"
            if societal_template not in include_items:
                include_items = ["expl_imperator_rome", societal_template] + [
                    x for x in include_items if x != "expl_imperator_rome"
                ]

        merged["include"] = include_items

        # --- simple defaults ---
        merged.setdefault("country_rank", "rank_county")
        if rank_map:
            merged["country_rank"] = rank_map.get(tag, merged["country_rank"])
        merged.setdefault("capital", "REPLACE_ME")

        # --- apply IR capital if available ---
        if ir_country_capitals is not None and id_to_key is not None:
            cap_id = ir_country_capitals.get(tag)
            if cap_id is not None:
                cap_key = id_to_key.get(cap_id)
                if cap_key and (location_keys is None or cap_key in location_keys):
                    merged["capital"] = cap_key

        # --- ensure capital is a valid location ---
        if locations:
            cap = merged.get("capital")
            if cap in ("REPLACE_ME", None) or (
                location_keys is not None and cap not in location_keys
            ):
                merged["capital"] = locations[0]

        # --- emit ---
        lines: list = []
        lines.append(f"# {country_name}")

        for key, value in merged.items():
            if key == "include":
                for x in value:
                    lines.append(f'include = "{x}"')

            elif isinstance(value, dict):
                sub = []
                for k, v in value.items():
                    if isinstance(v, list):
                        sub.append((k, v))
                    else:
                        sub.append(f"{k} = {normalize_value(v)}")
                lines.append((key, sub))

            elif isinstance(value, list):
                lines.append((key, value))

            else:
                # strings, numbers, AND inline "{ }"
                lines.append(f"{key} = {normalize_value(value)}")

        blocks.append((tag, lines))

    nested = ("countries", [("countries", blocks)])
    top_line = "current_age = age_1_traditions"

    write_blocks_with_comments(
        iu_setup_start / "10_countries.txt",
        [top_line, nested],
        comment_tags=comment_tags,
    )

    # --- audit pass ---
    audit_country_locations(ten_countries_data, country_data, eu5_map_data)


def write_05_characters(five_characters_data, character_data):
    # --- helpers ---
    char_by_id = {c["id"]: c for c in character_data}
    character_map = {c["id"]: c["tag"] for c in character_data}

    # --- build parent dependencies ---
    deps = defaultdict(set)
    for c in character_data:
        cid = c["id"]
        if c.get("father"):
            deps[cid].add(c["father"])
        if c.get("mother"):
            deps[cid].add(c["mother"])

    # --- topological sort (parents first) ---
    indeg = {c["id"]: 0 for c in character_data}
    for child, parents in deps.items():
        indeg[child] += len(parents)

    queue = [cid for cid, d in indeg.items() if d == 0]
    topo_order = []

    while queue:
        cid = queue.pop(0)
        topo_order.append(cid)
        for c, parents in deps.items():
            if cid in parents:
                indeg[c] -= 1
                if indeg[c] == 0:
                    queue.append(c)

    # --- enforce spouse adjacency ---
    used = set()
    final_order = []

    for cid in topo_order:
        if cid in used:
            continue

        c = char_by_id[cid]
        spouse = c.get("spouse")

        if spouse and spouse not in used:
            final_order.append(cid)
            final_order.append(spouse)
            used.add(cid)
            used.add(spouse)
        else:
            final_order.append(cid)
            used.add(cid)

    # --- emit blocks ---
    blocks = []
    comment_tags = set()
    spouse_emitted = set()

    for cid in final_order:
        character = char_by_id[cid]

        tag = character["tag"]
        name = character["name"]
        name_tag = character["name_tag"]
        dynasty = character["dynasty_tag"]

        # --- start from base, preserve everything ---
        base = five_characters_data.get(tag, {})
        merged = dict(base)

        if name_tag:
            merged["first_name"] = f"{{ name = {name_tag} }}"
        else:
            merged["first_name"] = "random"

        if dynasty:
            merged["dynasty"] = dynasty

        # --- relations ---
        if character.get("father"):
            merged["father"] = character_map[character["father"]]
        if character.get("mother"):
            merged["mother"] = character_map[character["mother"]]

        if character.get("spouse") and cid not in spouse_emitted:
            merged["spouse"] = character_map[character["spouse"]]
            spouse_emitted.add(character["spouse"])

        # --- attributes ---
        if character.get("culture"):
            merged["culture"] = character["culture"]
        if character.get("female"):
            merged["female"] = "yes"
        if character.get("religion"):
            merged["religion"] = character["religion"]

        merged["tag"] = character["country"]
        merged["birth_date"] = character["birth_date"]
        if "death_date" in character and character["death_date"]:
            merged["death_date"] = character["death_date"]

        if character.get("nickname_tag"):
            merged["nickname"] = character["nickname_tag"]

        # --- emit ---
        lines = []
        comment = f"# {name}"
        if dynasty:
            comment += dynasty
        lines.append(comment)

        for key, value in merged.items():
            if isinstance(value, dict):
                sub = [f"{k} = {v}" for k, v in value.items()]
                lines.append((key, sub))
            elif isinstance(value, list):
                lines.append((key, value))
            else:
                lines.append(f"{key} = {value}")

        blocks.append((tag, lines))

    nested = ("character_db", blocks)

    write_blocks_with_comments(
        iu_setup_start / "05_characters.txt",
        [nested],
        comment_tags=comment_tags,
    )


