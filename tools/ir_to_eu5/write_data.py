def _language_to_dialect_id(lang_id: str | None) -> str | None:
    if not lang_id:
        return None
    if lang_id in ir_language_dialect_parent_map:
        return (
            lang_id.replace("_lang", "_dialect")
            if lang_id.endswith("_lang")
            else f"{lang_id}_dialect"
        )
    return lang_id


def _dialect_parent_language(lang_or_dialect: str | None) -> str | None:
    if not lang_or_dialect:
        return None
    if lang_or_dialect in ir_language_dialect_parent_map:
        return ir_language_dialect_parent_map[lang_or_dialect]
    if lang_or_dialect.endswith("_dialect"):
        candidate = lang_or_dialect.replace("_dialect", "_lang")
        return ir_language_dialect_parent_map.get(candidate, candidate)
    return lang_or_dialect


def _language_family_map_from_file(path: Path) -> dict[str, str]:
    if not path.exists():
        return {}
    from .extract_data import parse_tree

    tree = parse_tree(path)
    family_map: dict[str, str] = {}
    for lang_id, value in tree.items():
        block = value
        if isinstance(value, list) and value:
            block = value[0]
        if not isinstance(block, _pydt.Tree):
            continue
        fam = block.find("family")
        if isinstance(fam, list):
            fam = fam[0] if fam else ""
        family_map[lang_id] = str(fam) if fam else ""
    return family_map


def write_language_data_full(culture_data: list) -> None:
    """Ensure ir_languages.txt contains blocks for every IU language used."""
    out_path = iu_languages / "ir_languages.txt"
    from .extract_data import parse_tree
    import copy

    existing_tree = parse_tree(out_path) if out_path.exists() else _pydt.Tree()

    # Determine all language IDs that should exist.
    language_ids_raw = set(ir_culture_group_language_map.values())
    language_ids_raw.update(ir_culture_language_overrides.values())
    language_ids_raw.update(ir_language_base_color_map.keys())
    # Map dialect languages to their parent language.
    language_ids = {
        _dialect_parent_language(lang_id)
        for lang_id in language_ids_raw
        if lang_id
    }

    # Map language -> culture group (from culture data + group-language map)
    lang_groups: dict[str, set[str]] = defaultdict(set)
    for group in culture_data:
        group_tag = group.get("tag")
        for culture in group.get("cultures", []):
            culture_tag = culture.get("tag")
            culture_language = None
            if culture_tag:
                culture_language = ir_culture_language_overrides.get(culture_tag)
            if not culture_language and group_tag:
                culture_language = ir_culture_group_language_map.get(group_tag)
            # For group mapping, store the parent language (dialect parent).
            culture_language = _dialect_parent_language(culture_language)
            if culture_language and group_tag:
                lang_groups[culture_language].add(group_tag)
    # Ensure every group-mapped language retains a group association,
    # even if all cultures are overridden to sub-languages.
    for group_tag, lang_id in ir_culture_group_language_map.items():
        if group_tag and lang_id:
            lang_id = _dialect_parent_language(lang_id)
            lang_groups[lang_id].add(group_tag)

    # Build cache of base-game language blocks for reuse using pyradox.
    base_language_blocks: dict[str, _pydt.Tree] = {}
    base_languages_dir = eu5_game / "in_game" / "common" / "languages"
    if base_languages_dir.exists():
        for path in sorted(base_languages_dir.glob("*.txt")):
            tree = parse_tree(path)
            for base_key in set(ir_language_base_color_map.values()) | set(
                ir_culture_group_base_language_map.values()
            ):
                if base_key in base_language_blocks:
                    continue
                if base_key in tree:
                    block = tree[base_key]
                    if isinstance(block, list) and block:
                        block = block[0]
                    if isinstance(block, _pydt.Tree):
                        base_language_blocks[base_key] = block

    def infer_family(lang_id: str) -> str:
        groups = lang_groups.get(lang_id)
        if groups:
            group_tag = sorted(groups)[0]
            return _language_family_id_from_group_tag(group_tag)
        return ""

    def infer_base_key(lang_id: str) -> str | None:
        base_key = ir_language_base_color_map.get(lang_id)
        if base_key:
            return base_key
        groups = lang_groups.get(lang_id)
        if not groups:
            return None
        group_tag = sorted(groups)[0]
        return ir_culture_group_base_language_map.get(group_tag)

    # Parent language -> list of dialect source language IDs.
    parent_to_dialects: dict[str, list[str]] = defaultdict(list)
    for child_lang, parent_lang in ir_language_dialect_parent_map.items():
        if parent_lang:
            parent_to_dialects[parent_lang].append(child_lang)

    out_tree = _pydt.Tree()
    for lang_id in sorted(language_ids):
        block = existing_tree[lang_id] if lang_id in existing_tree else None
        if isinstance(block, list) and block:
            block = block[0]
        base_key = infer_base_key(lang_id)
        base_block = (
            copy.deepcopy(base_language_blocks[base_key])
            if base_key and base_key in base_language_blocks
            else None
        )

        def is_placeholder(tree: _pydt.Tree) -> bool:
            keys = {k for k, _ in tree.items()}
            return keys.issubset({"color", "family"})

        if isinstance(block, _pydt.Tree) and not is_placeholder(block):
            out_block = copy.deepcopy(block)
        elif base_block is not None:
            out_block = base_block
        elif isinstance(block, _pydt.Tree):
            out_block = copy.deepcopy(block)
        else:
            out_block = _pydt.Tree()
            out_block["color"] = _pydt.Color("rgb", [128, 128, 128])

        # Remove copied dialects to avoid duplicate dialect IDs across languages.
        if "dialects" in out_block:
            del out_block["dialects"]

        # Add IU dialects when configured.
        dialect_children = parent_to_dialects.get(lang_id, [])
        if dialect_children:
            dialects_tree = _pydt.Tree()
            for child_lang in sorted(dialect_children):
                dialect_id = (
                    child_lang.replace("_lang", "_dialect")
                    if child_lang.endswith("_lang")
                    else f"{child_lang}_dialect"
                )
                dialects_tree.append(dialect_id, _pydt.Tree())
            out_block["dialects"] = dialects_tree

        family_id = infer_family(lang_id)
        if family_id:
            # Always override to ensure IU family IDs are used.
            out_block["family"] = family_id

        out_tree[lang_id] = out_block

    # Write with a manual header; do NOT auto-generate elsewhere.
    header = (
        "# =========================================================== #\n"
        "#         THIS FILE IS MANUALLY CURATED. DO NOT              #\n"
        "#           AUTO-GENERATE OR OVERWRITE.                      #\n"
        "# =========================================================== #\n\n"
    )
    blocks = convert_tree_to_blocks(out_tree)
    content = [header]
    for block in blocks:
        if isinstance(block, tuple) and len(block) == 2:
            tag, lines = block
            content.append(make_block(tag, lines, indent_level=0, indent_str="    "))
            content.append("\n")
        else:
            content.append(str(block))
            if not str(block).endswith("\n"):
                content.append("\n")
            content.append("\n")
    out_path.write_text("".join(content), encoding="utf-8-sig")
    print_written("file", out_path)
def print_written(kind: str, out_path: Path) -> None:
    """Print a concise relative write message for `out_path`.

    `kind` should be a short label like 'file', 'JSON', 'CSV', or 'image'.
    """
    try:
        rel = os.path.relpath(str(out_path), start=str(mod_root))
    except Exception:
        rel = str(out_path)
    print(f"Writing {kind}: {rel}")


def convert_color(color: _pydt.Color) -> str:
    if color.colorspace == "rgb":
        r, g, b = color.channels
        return f"rgb {{ {r} {g} {b} }}"
    elif color.colorspace == "hsv":
        h, s, v = color.channels
        return f"hsv {{ {h:.2f} {s:.2f} {v:.2f} }}"
    else:
        raise ValueError(f"Unsupported color space: {color.colorspace}")


def convert_tree_to_blocks(
    tree: _pydt.Tree,
) -> List[Union[str, Tuple[str, List[object]]]]:
    blocks: List[Union[str, Tuple[str, List[object]]]] = []

    grouped: dict[str, list] = {}

    # Group repeated keys
    for key, value in tree.items():
        if key not in grouped:
            grouped[key] = []
        grouped[key].append(value)

    for key, values in grouped.items():
        # All scalar values → aggregate into one line
        if all(not isinstance(v, (_pydt.Tree, list)) for v in values):
            formatted_values = [_pytoken.make_token_string(v) for v in values]
            if len(formatted_values) == 1:
                blocks.append(f"{key} = {formatted_values[0]}")
            else:
                items = " ".join(formatted_values)
                blocks.append(f"{key} = {{ {items} }}")
            continue

        # Lists of scalars → emit a single brace block
        if all(isinstance(v, list) for v in values):
            flat: list[object] = []
            has_complex = False
            for v in values:
                for item in v:
                    if isinstance(item, (_pydt.Tree, list)):
                        has_complex = True
                        break
                    flat.append(item)
                if has_complex:
                    break
            if not has_complex:
                formatted = " ".join(_pytoken.make_token_string(item) for item in flat)
                blocks.append(f"{key} = {{ {formatted} }}")
                continue

        # Complex values: trees or lists
        for v in values:
            if isinstance(v, _pydt.Tree):
                # Use the parent key as the tag, not the "tag" inside the tree
                subblocks = convert_tree_to_blocks(v)
                blocks.append((key, subblocks))
            elif isinstance(v, list):
                for item in v:
                    if isinstance(item, _pydt.Tree):
                        # Again, parent key is used to avoid double nesting
                        subblocks = convert_tree_to_blocks(item)
                        blocks.append((key, subblocks))
                    else:
                        # Scalar inside a list
                        formatted = _pytoken.make_token_string(item)
                        blocks.append(f"{key} = {formatted}")

    return blocks


def make_block(
    tag: str,
    lines: List[Union[str, Tuple[str, List[object]]]] | None = None,
    indent_level: int = 0,
    indent_str: str = "    ",
) -> str:
    if lines is None:
        lines = []

    prefix = indent_str * indent_level
    inner_prefix = prefix + indent_str

    parts: List[str] = [f"{prefix}{tag} = {{\n"]

    for line in lines:
        if isinstance(line, tuple) and len(line) == 2:
            subtag, sublines = line
            parts.append(make_block(subtag, sublines, indent_level + 1, indent_str))
        else:
            parts.append(f"{inner_prefix}{line}\n")

    parts.append(f"{prefix}}}\n")
    return "".join(parts)


def write_blocks(
    out_path: Path,
    blocks: Union[
        str,
        Tuple[str, List[object]],
        List[Union[str, Tuple[str, List[object]]]],
    ],
    mode: str = "w",
    encoding: str = "utf-8-sig",
    indent_str: str = "    ",
) -> Path:
    # normalize to a list of blocks
    if isinstance(blocks, (tuple, str)):
        blocks_list = [blocks]
    elif isinstance(blocks, list):
        blocks_list = blocks
    elif isinstance(blocks, _pydt.Tree):
        blocks_list = convert_tree_to_blocks(blocks)
    else:
        raise TypeError("blocks must be a str, a (tag, lines) tuple, or a list")

    out_path.parent.mkdir(parents=True, exist_ok=True)

    with out_path.open(mode, encoding=encoding) as f:
        # --- header ---
        f.write(AUTO_GENERATED_HEADER)

        for block in blocks_list:
            if isinstance(block, tuple) and len(block) == 2:
                tag, lines = block
                content = make_block(tag, lines, indent_level=0, indent_str=indent_str)
                # Collapse accidental double-empty-brace sequences (e.g. "{ {} }")
                content = content.replace("{ {} }", "{}")
                f.write(content)
                f.write("\n")
            else:
                s = str(block)
                s = s.replace("{ {} }", "{}")
                f.write(s)
                if not s.endswith("\n"):
                    f.write("\n")
                if out_path.suffix not in (".yml", ".yaml"):
                    f.write("\n")

    print_written("file", out_path)
    return out_path


