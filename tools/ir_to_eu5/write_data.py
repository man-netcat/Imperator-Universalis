AUTO_GENERATED_HEADER = (
    "# =========================================================== #\n"
    "#            THIS FILE IS AUTOMATICALLY GENERATED!            #\n"
    "#  Any manual changes will be OVERWRITTEN upon regeneration!  #\n"
    "# =========================================================== #\n\n"
)


def ensure_list(value):
    return value if isinstance(value, list) else [value]


def _dedupe(items: list) -> list:
    seen = set()
    out = []
    for item in items:
        if item in seen:
            continue
        seen.add(item)
        out.append(item)
    return out


def print_written(kind: str, out_path: Path) -> None:
    """Print a concise relative write message for `out_path`.

    `kind` should be a short label like 'file', 'JSON', 'CSV', or 'image'.
    """
    try:
        rel = os.path.relpath(str(out_path), start=str(mod_root))
    except Exception:
        rel = str(out_path)
    print(f"Writing {kind}: {rel}")


def convert_color(color: _pydt.Color) -> str:
    if color.colorspace == "rgb":
        r, g, b = color.channels
        return f"rgb {{ {r} {g} {b} }}"
    elif color.colorspace == "hsv":
        h, s, v = color.channels
        return f"hsv {{ {h:.2f} {s:.2f} {v:.2f} }}"
    else:
        raise ValueError(f"Unsupported color space: {color.colorspace}")


def convert_tree_to_blocks(
    tree: _pydt.Tree,
) -> List[Union[str, Tuple[str, List[object]]]]:
    blocks: List[Union[str, Tuple[str, List[object]]]] = []

    grouped: dict[str, list] = {}

    # Group repeated keys
    for key, value in tree.items():
        if key not in grouped:
            grouped[key] = []
        grouped[key].append(value)

    for key, values in grouped.items():
        # All scalar values → aggregate into one line
        if all(not isinstance(v, (_pydt.Tree, list)) for v in values):
            formatted_values = [_pytoken.make_token_string(v) for v in values]
            if len(formatted_values) == 1:
                blocks.append(f"{key} = {formatted_values[0]}")
            else:
                items = " ".join(formatted_values)
                blocks.append(f"{key} = {{ {items} }}")

        else:
            # Complex values: trees or lists
            for v in values:
                if isinstance(v, _pydt.Tree):
                    # Use the parent key as the tag, not the "tag" inside the tree
                    subblocks = convert_tree_to_blocks(v)
                    blocks.append((key, subblocks))
                elif isinstance(v, list):
                    for item in v:
                        if isinstance(item, _pydt.Tree):
                            # Again, parent key is used to avoid double nesting
                            subblocks = convert_tree_to_blocks(item)
                            blocks.append((key, subblocks))
                        else:
                            # Scalar inside a list
                            formatted = _pytoken.make_token_string(item)
                            blocks.append(f"{key} = {formatted}")

    return blocks


def make_block(
    tag: str,
    lines: List[Union[str, Tuple[str, List[object]]]] | None = None,
    indent_level: int = 0,
    indent_str: str = "    ",
) -> str:
    if lines is None:
        lines = []

    prefix = indent_str * indent_level
    inner_prefix = prefix + indent_str

    parts: List[str] = [f"{prefix}{tag} = {{\n"]

    for line in lines:
        if isinstance(line, tuple) and len(line) == 2:
            subtag, sublines = line
            parts.append(make_block(subtag, sublines, indent_level + 1, indent_str))
        else:
            parts.append(f"{inner_prefix}{line}\n")

    parts.append(f"{prefix}}}\n")
    return "".join(parts)


def write_blocks(
    out_path: Path,
    blocks: Union[
        str,
        Tuple[str, List[object]],
        List[Union[str, Tuple[str, List[object]]]],
    ],
    mode: str = "w",
    encoding: str = "utf-8-sig",
    indent_str: str = "    ",
) -> Path:
    # normalize to a list of blocks
    if isinstance(blocks, (tuple, str)):
        blocks_list = [blocks]
    elif isinstance(blocks, list):
        blocks_list = blocks
    elif isinstance(blocks, _pydt.Tree):
        blocks_list = convert_tree_to_blocks(blocks)
    else:
        raise TypeError("blocks must be a str, a (tag, lines) tuple, or a list")

    out_path.parent.mkdir(parents=True, exist_ok=True)

    with out_path.open(mode, encoding=encoding) as f:
        # --- header ---
        f.write(AUTO_GENERATED_HEADER)

        for block in blocks_list:
            if isinstance(block, tuple) and len(block) == 2:
                tag, lines = block
                content = make_block(tag, lines, indent_level=0, indent_str=indent_str)
                # Collapse accidental double-empty-brace sequences (e.g. "{ {} }")
                content = content.replace("{ {} }", "{}")
                f.write(content)
                f.write("\n")
            else:
                s = str(block)
                s = s.replace("{ {} }", "{}")
                f.write(s)
                if not s.endswith("\n"):
                    f.write("\n")
                if out_path.suffix not in (".yml", ".yaml"):
                    f.write("\n")

    print_written("file", out_path)
    return out_path


def _existing_block_map(path: Path) -> dict[str, _pydt.Tree]:
    return {}


def _merge_tree_with_overrides(
    existing: _pydt.Tree | None,
    overrides: dict[str, object],
    add_if_missing: dict[str, object] | None = None,
) -> _pydt.Tree:
    merged = _pydt.Tree(existing) if existing is not None else _pydt.Tree()
    for key, value in overrides.items():
        merged[key] = value
    if add_if_missing:
        for key, value in add_if_missing.items():
            if key not in merged:
                merged.append(key, value)
    return merged


def _append_existing_blocks(
    blocks: list,
    existing_blocks: dict[str, _pydt.Tree],
    generated_tags: set[str],
) -> None:
    for tag, tree in existing_blocks.items():
        if tag not in generated_tags:
            lines = convert_tree_to_blocks(tree)
            blocks.append((tag, lines))


def _map_religion(raw_religion: str | None, religion_tags: set[str]) -> str | None:
    mapped = PANTHEON_MAP.get(raw_religion)
    if not mapped and raw_religion:
        candidate = f"ir_{raw_religion}"
        if candidate in religion_tags:
            mapped = candidate
    return mapped


def _build_country_rank_map(
    ir_country_locations: dict[str, list[int]],
    country_data: list[dict] | None = None,
) -> dict[str, str]:
    sizes = {tag: len(locs) for tag, locs in ir_country_locations.items()}
    if not sizes:
        return {}

    county_max = 3
    duchy_max = 14
    kingdom_max = 249

    government_by_tag: dict[str, str] = {}
    if country_data:
        for country in country_data:
            tag = country.get("tag")
            if tag:
                government_by_tag[tag] = country.get("government")

    monarchies = {
        "aristocratic_monarchy",
        "despotic_monarchy",
        "stratocratic_monarchy",
        "plutocratic_monarchy",
        "spartan_monarchy",
        "tribal_kingdom"
    }

    rank_map: dict[str, str] = {}
    for tag, size in sizes.items():
        if size <= county_max:
            rank = "rank_county"
        elif size <= duchy_max:
            rank = "rank_duchy"
        elif size <= kingdom_max:
            rank = "rank_kingdom"
        else:
            rank = "rank_empire"
        ir_gov = government_by_tag.get(tag)
        if ir_gov in monarchies:
            if rank in ("rank_county", "rank_duchy"):
                rank = "rank_kingdom"

        rank_map[tag] = rank

    return rank_map


