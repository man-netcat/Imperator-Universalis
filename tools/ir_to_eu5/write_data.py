    def _esc_loc(value: object) -> str:
        return str(value).replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")

    def sort_lines(lines: list[str]) -> list[str]:
        """Keep the first line (header) and sort the rest alphabetically."""
        return [lines[0]] + sorted(lines[1:])

    def remove_duplicate_keys(lines: list[str]) -> list[str]:
        """Remove duplicate keys, keeping only the first occurrence."""
        header, *body = lines
        seen_keys = set()
        unique_lines = []
        for line in body:
            key = line.split(":", 1)[0].strip()
            if key not in seen_keys:
                seen_keys.add(key)
                unique_lines.append(line)
        return [header] + unique_lines

    def _collect_block_ids(path: Path) -> list[str]:
        if not path.exists():
            return []
        from .extract_data import parse_tree

        tree = parse_tree(path)
        return [key for key in tree.keys() if isinstance(key, str)]

    def _collect_dialect_ids(path: Path) -> list[str]:
        if not path.exists():
            return []
        from .extract_data import parse_tree

        tree = parse_tree(path)
        dialects: list[str] = []
        for _lang_id, value in tree.items():
            block = value
            if isinstance(block, list) and block:
                block = block[0]
            if not isinstance(block, _pydt.Tree):
                continue
            dialects_block = block.find("dialects")
            if not isinstance(dialects_block, _pydt.Tree):
                continue
            for dialect_id in dialects_block.keys():
                if isinstance(dialect_id, str):
                    dialects.append(dialect_id)
        return dialects

    def _humanize_ir_id(tag: str) -> str:
        base = tag
        if base.startswith("ir_"):
            base = base[3:]
        if base.endswith("_lang"):
            base = base[: -len("_lang")]
        if base.endswith("_family"):
            base = base[: -len("_family")]
        if base.endswith("_dialect"):
            base = base[: -len("_dialect")]

        specials = {
            "indo_aryan": "Indo-Aryan",
            "indo_iranian": "Indo-Iranian",
            "proto_baltic": "Proto-Baltic",
            "proto_germanic": "Proto-Germanic",
            "proto_finnic": "Proto-Finnic",
            "proto_european": "Proto-European",
            "old_chinese": "Old Chinese",
            "old_south_arabian": "Old South Arabian",
            "magadhan_prakrit": "Magadhan Prakrit",
            "pannonian_celtic": "Pannonian Celtic",
            "celtiberian": "Celtiberian",
            "goidelic": "Goidelic",
            "brittonic": "Brittonic",
            "geez": "Geez",
        }
        if base in specials:
            return specials[base]
        return " ".join(word.capitalize() for word in base.split("_"))

